/**
 * Renders deploy/collector/config.yaml from the path rule set, so the
 * Collector and the writer always normalize paths the same way.
 *
 *   node scripts/gen-collector-config.ts          writes the file
 *   node scripts/gen-collector-config.ts --check  fails if the file is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { toOttlStatements } from "../packages/path-rules/src/index.ts";

const ROUTE = "parallax.route";
const target = new URL("../deploy/collector/config.yaml", import.meta.url);

function yamlString(value: string): string {
  // Single-quoted YAML scalars only need single quotes doubled.
  return `'${value.replaceAll("'", "''")}'`;
}

export function render(): string {
  const routeStatements = [
    `set(attributes["${ROUTE}"], attributes["http.route"]) where attributes["http.route"] != nil`,
    `set(attributes["${ROUTE}"], attributes["url.path"]) where attributes["${ROUTE}"] == nil and attributes["url.path"] != nil`,
    `set(attributes["${ROUTE}"], attributes["http.target"]) where attributes["${ROUTE}"] == nil and attributes["http.target"] != nil`,
    `set(attributes["${ROUTE}"], "/{unknown}") where attributes["${ROUTE}"] == nil`,
    ...toOttlStatements(ROUTE),
    `set(attributes["parallax.status"], attributes["http.response.status_code"]) where attributes["http.response.status_code"] != nil`,
    `set(attributes["parallax.status"], attributes["http.status_code"]) where attributes["parallax.status"] == nil and attributes["http.status_code"] != nil`,
    `set(attributes["parallax.method"], attributes["http.request.method"]) where attributes["http.request.method"] != nil`,
    `set(attributes["parallax.method"], attributes["http.method"]) where attributes["parallax.method"] == nil and attributes["http.method"] != nil`,
    // Everything else on the span is dropped here, before any metric exists.
    `keep_keys(attributes, ["${ROUTE}", "parallax.status", "parallax.method"])`,
    `set(name, "request")`,
  ];
  const statements = routeStatements.map((s) => `          - ${yamlString(s)}`).join("\n");

  return `# GENERATED by scripts/gen-collector-config.ts. Do not edit by hand.
# Path rules come from packages/path-rules; run \`pnpm gen:collector\` after changing them.
#
# What this pipeline does:
#   traces  -> keep server spans, set the tenant from the gateway, normalize the
#              path, strip every other attribute, count requests and durations,
#              then DROP the spans. Only the derived metrics go on.
#   metrics -> dropped (deriving from a tenant's own HTTP metrics is on the roadmap).
#   logs    -> dropped.

extensions:
  health_check:
    endpoint: 0.0.0.0:13133

receivers:
  otlp:
    protocols:
      http:
        endpoint: 0.0.0.0:4318
        include_metadata: true

processors:
  memory_limiter:
    check_interval: 1s
    limit_percentage: 75
    spike_limit_percentage: 20
  filter/server-spans:
    error_mode: ignore
    traces:
      span:
        - 'kind != SPAN_KIND_SERVER'
  resource/tenant:
    attributes:
      # Set by the ingest gateway from the tenant's API key. Whatever the
      # tenant sent under this name is overwritten.
      - key: parallax.tenant
        from_context: metadata.x-parallax-tenant
        action: upsert
  transform/route:
    error_mode: ignore
    trace_statements:
      - context: span
        statements:
${statements}

connectors:
  span_metrics:
    histogram:
      unit: ms
      explicit:
        buckets: [5ms, 10ms, 25ms, 50ms, 100ms, 250ms, 500ms, 1s, 2.5s, 5s, 10s]
    dimensions:
      - name: ${ROUTE}
      - name: parallax.status
      - name: parallax.method
    exclude_dimensions: [span.name, span.kind, status.code]
    resource_metrics_key_attributes: [service.name, parallax.tenant]
    aggregation_temporality: AGGREGATION_TEMPORALITY_DELTA
    metrics_flush_interval: 15s

exporters:
  otlp_http/writer:
    endpoint: \${env:PARALLAX_WRITER_URL}
    encoding: json
    compression: none
    headers:
      x-internal-key: \${env:PARALLAX_INTERNAL_KEY}
  nop:

service:
  extensions: [health_check]
  telemetry:
    logs:
      level: warn
  pipelines:
    traces:
      receivers: [otlp]
      processors: [memory_limiter, resource/tenant, filter/server-spans, transform/route]
      exporters: [span_metrics]
    metrics/derived:
      receivers: [span_metrics]
      exporters: [otlp_http/writer]
    metrics/dropped:
      receivers: [otlp]
      exporters: [nop]
    logs/dropped:
      receivers: [otlp]
      exporters: [nop]
`;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll("\\", "/").split("/").pop() ?? "")) {
  const output = render();
  if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8").replaceAll("\r\n", "\n");
    if (current !== output) {
      console.error("deploy/collector/config.yaml is stale. Run `pnpm gen:collector`.");
      process.exit(1);
    }
    console.log("collector config is up to date");
  } else {
    writeFileSync(target, output);
    console.log("wrote deploy/collector/config.yaml");
  }
}
